import fs from "fs";
import path from "path";

const DOCS_ROOT = path.resolve(process.argv[2] || "../docs");
const OUT_FILE = path.resolve("./src/docs/_generated-docs.ts");

function walk(dir, list = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, list);
    } else if (entry.name.endsWith(".md")) {
      list.push(full);
    }
  }
  return list;
}

const files = walk(DOCS_ROOT);
const entries = [];

for (const file of files) {
  const relative = path.relative(DOCS_ROOT, file).replace(/\\/g, "/");
  const raw = fs.readFileSync(file, "utf-8");
  entries.push({ path: relative, content: raw });
}

const header = `// AUTO-GENERATED by scripts/generate-docs-catalog.mjs — DO NOT EDIT
// Run: node scripts/generate-docs-catalog.mjs
// Provides bundled markdown content so the docs catalog works on ALL platforms including web.

export interface BundledDocEntry {
\tpath: string;
\tcontent: string;
}

export const bundledDocs: BundledDocEntry[] = [\n`;

const body = entries
  .map(({ path: p, content }) => {
    const escaped = content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
    return `\t{ path: ${JSON.stringify(p)}, content: \`${escaped}\` },`;
  })
  .join("\n");

const footer = `\n];\n`;

fs.writeFileSync(OUT_FILE, header + body + footer);
console.log(`Generated ${OUT_FILE} with ${entries.length} docs from ${DOCS_ROOT}`);
